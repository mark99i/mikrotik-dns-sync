"""Офлайн-тесты load_config: валидация, значения по умолчанию, ошибки."""

import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from main import SyncError, load_config
from tests.util import TmpFiles


class LoadConfigTest(unittest.TestCase):
    def setUp(self):
        self.tmp = TmpFiles("config")
        self._saved_env: dict[str, str | None] = {}

    def tearDown(self):
        self.tmp.cleanup()
        for name, old in self._saved_env.items():
            if old is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = old

    def _setenv(self, name: str, value: str):
        self._saved_env[name] = os.environ.get(name)
        os.environ[name] = value

    def _cfg(self, data, filename: str = "config.json") -> str:
        path = self.tmp.path(filename)
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(data, fh)
        return path

    def _dev(self, **kw) -> dict:
        base = dict(name="gw", host="192.0.2.1", username="u", password="p",
                    address_list="L")
        base.update(kw)
        return base

    # -- корректные конфиги --

    def test_minimal_valid(self):
        cfg = load_config(self._cfg({"devices": [self._dev()]}))
        self.assertEqual(len(cfg.devices), 1)
        d = cfg.devices[0]
        self.assertEqual((d.scheme, d.port, d.verify, d.timeout, d.enabled),
                         ("https", 443, False, 15.0, True))
        self.assertEqual((cfg.delete_comment, cfg.adopt_foreign, cfg.max_workers),
                         ("del", True, 4))

    def test_http_scheme_default_port(self):
        cfg = load_config(self._cfg({"devices": [self._dev(scheme="http")]}))
        self.assertEqual((cfg.devices[0].scheme, cfg.devices[0].port), ("http", 80))

    def test_explicit_port_kept(self):
        cfg = load_config(self._cfg({"devices": [self._dev(port=8443)]}))
        self.assertEqual(cfg.devices[0].port, 8443)

    def test_password_env(self):
        self._setenv("TEST_SYNC_PASS", "s3cret")
        cfg = load_config(self._cfg(
            {"devices": [self._dev(password=None, password_env="TEST_SYNC_PASS")]}))
        self.assertEqual(cfg.devices[0].password, "s3cret")

    def test_verify_ca_cert(self):
        cfg = load_config(self._cfg(
            {"devices": [self._dev(verify_ssl=True, ca_cert="rest-ca.crt")]}))
        self.assertEqual(cfg.devices[0].verify, "rest-ca.crt")

    def test_verify_ssl_true_without_ca(self):
        cfg = load_config(self._cfg({"devices": [self._dev(verify_ssl=True)]}))
        self.assertIs(cfg.devices[0].verify, True)

    def test_disabled_device(self):
        cfg = load_config(self._cfg({"devices": [self._dev(enabled=False)]}))
        self.assertFalse(cfg.devices[0].enabled)

    def test_timeout_as_string(self):
        cfg = load_config(self._cfg({"timeout": "20", "devices": [self._dev()]}))
        self.assertEqual(cfg.devices[0].timeout, 20.0)

    def test_max_workers_clamped_to_one(self):
        cfg = load_config(self._cfg({"max_workers": 0, "devices": [self._dev()]}))
        self.assertEqual(cfg.max_workers, 1)

    def test_max_workers_as_string(self):
        cfg = load_config(self._cfg({"max_workers": "8", "devices": [self._dev()]}))
        self.assertEqual(cfg.max_workers, 8)

    def test_device_name_autogenerated(self):
        dev = self._dev()
        del dev["name"]
        cfg = load_config(self._cfg({"devices": [dev]}))
        self.assertEqual(cfg.devices[0].name, "device-1")

    def test_delete_comment_null_falls_back_to_default(self):
        cfg = load_config(self._cfg({"delete_comment": None,
                                     "devices": [self._dev()]}))
        self.assertEqual(cfg.delete_comment, "del")

    def test_devices_must_be_list(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"devices": "oops"}))
        self.assertIn("devices", str(ctx.exception))

    # -- ошибки конфигурации (код возврата 3) --

    def test_file_not_found(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self.tmp.path("missing.json"))
        self.assertIn("не найден", str(ctx.exception))

    def test_bad_json(self):
        path = self.tmp.path("broken.json5")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("{not json5")
        with self.assertRaises(SyncError):
            load_config(path)

    def test_default_forward_to(self):
        cfg = load_config(self._cfg({"default_forward_to": " 10.0.0.53 ",
                                     "devices": [self._dev()]}))
        self.assertEqual(cfg.default_forward_to, "10.0.0.53")
        # по умолчанию — не задан
        cfg = load_config(self._cfg({"devices": [self._dev()]}))
        self.assertEqual(cfg.default_forward_to, "")

    def test_exclude_domains(self):
        dev = self._dev(exclude_domains=["  Local.Corp ", "printer.lan", ""])
        cfg = load_config(self._cfg({"devices": [dev]}))
        self.assertEqual(cfg.devices[0].exclude_domains,
                         ["local.corp", "printer.lan"])
        # одна строка вместо списка
        cfg = load_config(self._cfg({"devices": [self._dev(exclude_domains="x.com")]}))
        self.assertEqual(cfg.devices[0].exclude_domains, ["x.com"])
        # по умолчанию — пусто
        cfg = load_config(self._cfg({"devices": [self._dev()]}))
        self.assertEqual(cfg.devices[0].exclude_domains, [])

    def test_json5_syntax_supported(self):
        # комментарии, одинарные кавычки, некавыченные ключи, висячая запятая
        path = self.tmp.path("json5-config.json5")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("""// конфиг в формате JSON5
{
  delete_comment: 'DEL',  // регистр не важен
  devices: [
    {
      name: 'gw',
      host: '192.0.2.1',
      username: 'u',
      password: 'p',
      address_list: 'L',
    },
  ],
}
""")
        cfg = load_config(path)
        self.assertEqual(cfg.delete_comment, "del")
        self.assertEqual(cfg.devices[0].name, "gw")

    def test_not_an_object(self):
        with self.assertRaises(SyncError):
            load_config(self._cfg([1, 2]))

    def test_no_devices(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"devices": []}))
        self.assertIn("нет устройств", str(ctx.exception))

    def test_duplicate_device_names(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"devices": [self._dev(), self._dev()]}))
        self.assertIn("дубликат", str(ctx.exception))

    def test_required_fields(self):
        for req in ("host", "username", "address_list"):
            with self.subTest(field=req):
                dev = self._dev()
                dev[req] = ""
                with self.assertRaises(SyncError) as ctx:
                    load_config(self._cfg({"devices": [dev]}))
                self.assertIn(req, str(ctx.exception))

    def test_password_missing(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"devices": [self._dev(password=None)]}))
        self.assertIn("password", str(ctx.exception))

    def test_password_env_not_set(self):
        os.environ.pop("TEST_SYNC_PASS_MISSING", None)
        with self.assertRaises(SyncError):
            load_config(self._cfg(
                {"devices": [self._dev(password=None, password_env="TEST_SYNC_PASS_MISSING")]}))

    def test_bad_timeout(self):
        for bad in ("abc", 0, -1, None):
            with self.subTest(value=bad):
                with self.assertRaises(SyncError) as ctx:
                    load_config(self._cfg({"timeout": bad, "devices": [self._dev()]}))
                self.assertIn("timeout", str(ctx.exception))

    def test_bad_port(self):
        for bad in ("x", 0, 70000):
            with self.subTest(value=bad):
                with self.assertRaises(SyncError) as ctx:
                    load_config(self._cfg({"devices": [self._dev(port=bad)]}))
                self.assertIn("port", str(ctx.exception))

    def test_bad_scheme(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"devices": [self._dev(scheme="ftp")]}))
        self.assertIn("scheme", str(ctx.exception))

    def test_max_workers_garbage(self):
        with self.assertRaises(SyncError) as ctx:
            load_config(self._cfg({"max_workers": "abc", "devices": [self._dev()]}))
        self.assertIn("max_workers", str(ctx.exception))

    # -- предупреждения об неизвестных ключах --

    def test_unknown_top_keys_warn(self):
        data = {"devices": [self._dev()], "prune_stale": True, "bogus": 1}
        with self.assertLogs("dns-sync", level="WARNING") as captured:
            load_config(self._cfg(data))
        text = "\n".join(captured.output)
        self.assertIn("prune_stale", text)
        self.assertIn("delete_comment", text)   # подсказка, чем заменить
        self.assertIn("bogus", text)

    def test_unknown_device_keys_warn(self):
        dev = self._dev(force=True)
        with self.assertLogs("dns-sync", level="WARNING") as captured:
            load_config(self._cfg({"devices": [dev]}))
        self.assertIn("force", "\n".join(captured.output))


if __name__ == "__main__":
    unittest.main()
